/// <summary>The compensation/detail payload shared by create/override (US-PRF-010 FR-1/BR-5).</summary>
public sealed record RecommendationDetailsRequest(
    string? TargetGrade,
    string? TargetTitle,
    DateOnly? EffectiveDate,
    decimal? BonusAmount,
    decimal? BonusPercent,
    decimal? IncrementAmount,
    decimal? IncrementPercent,
    string? TrainingCourse,
    string? CustomTypeLabel,
    Guid? BudgetId);

/// <summary>Manually create OR override a recommendation for an employee in a cycle (US-PRF-010 FR-1/FR-3/BR-5).</summary>
public sealed record SaveRecommendationRequest(
    Guid EmployeeId,
    Guid CycleId,
    RecommendationType Type,
    RecommendationDetailsRequest Details,
    string? Justification);

/// <summary>Auto-generate recommendation suggestions across a cycle (US-PRF-010 AC-2/FR-2/BR-3).</summary>
public sealed record AutoGenerateRecommendationsRequest(Guid CycleId);

/// <summary>Submit a recommendation into the approval workflow (US-PRF-010 AC-3/FR-4).</summary>
public sealed record SubmitRecommendationRequest(IReadOnlyList<Guid>? ApproverEmployeeIds);

/// <summary>An approver's approve/reject decision (US-PRF-010 FR-4).</summary>
public sealed record DecideRecommendationRequest(string? Comment);

/// <summary>Create or update the cycle's bonus/increment budget (US-PRF-010 FR-8).</summary>
public sealed record SaveBudgetRequest(Guid CycleId, string Name, decimal AllocatedAmount, string? Currency);

/// <summary>Create or update an auto-generation rule (US-PRF-010 FR-2).</summary>
public sealed record SaveRuleRequest(
    string Name,
    decimal MinFinalScore,
    RecommendationType RecommendedType,
    decimal? DefaultBonusPercent,
    decimal? DefaultIncrementPercent,
    bool IsActive);

