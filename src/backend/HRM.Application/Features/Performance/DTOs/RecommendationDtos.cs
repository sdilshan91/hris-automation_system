/// <summary>One approver step in a recommendation's approval chain (US-PRF-010 FR-4).</summary>
public sealed record RecommendationApproverDto
{
    public Guid Id { get; init; }
    public Guid ApproverEmployeeId { get; init; }
    public string ApproverName { get; init; } = string.Empty;
    public int StepOrder { get; init; }
    public RecommendationApproverDecision Decision { get; init; }
    public string DecisionName { get; init; } = string.Empty;
    public DateTime? DecidedAt { get; init; }
    public string? Comment { get; init; }
}

/// <summary>One immutable recommendation audit-log entry (US-PRF-010 FR-4/FR-7).</summary>
public sealed record RecommendationEventDto
{
    public Guid Id { get; init; }
    public RecommendationEventType EventType { get; init; }
    public string EventTypeName { get; init; } = string.Empty;
    public string ActorName { get; init; } = string.Empty;
    public DateTime OccurredAt { get; init; }
    public string? Detail { get; init; }
}

/// <summary>
/// A full recommendation record (US-PRF-010). Returned from generate/override/submit/approve/reject and the
/// workspace get. Includes the FR-5 current-vs-recommended comparison fields, the approval chain (FR-4) and the
/// immutable event history (FR-7). Compensation fields are sensitive (NFR-3 seam) — served to authorized HR.
/// </summary>
public sealed record RecommendationDto
{
    public Guid Id { get; init; }
    public Guid EmployeeId { get; init; }
    public string EmployeeName { get; init; } = string.Empty;
    public string EmployeeNo { get; init; } = string.Empty;
    public Guid CycleId { get; init; }
    public Guid? ManagerReviewId { get; init; }

    public RecommendationType Type { get; init; }
    public string TypeName { get; init; } = string.Empty;
    public RecommendationStatus Status { get; init; }
    public string StatusName { get; init; } = string.Empty;
    public bool IsAutoGenerated { get; init; }

    // FR-5 comparison (current vs recommended).
    public string? CurrentGrade { get; init; }
    public string? TargetGrade { get; init; }
    public string? CurrentTitle { get; init; }
    public string? TargetTitle { get; init; }
    public DateOnly? EffectiveDate { get; init; }
    public decimal? CurrentCompensation { get; init; }

    // Compensation details (NFR-3 seam).
    public decimal? BonusAmount { get; init; }
    public decimal? BonusPercent { get; init; }
    public decimal? IncrementAmount { get; init; }
    public decimal? IncrementPercent { get; init; }

    public string? TrainingCourse { get; init; }
    public string? CustomTypeLabel { get; init; }
    public string? Justification { get; init; }
    public string? AutoGenerationRationale { get; init; }

    public Guid? BudgetId { get; init; }
    public decimal BudgetCharge { get; init; }

    public DateTime? SubmittedAt { get; init; }
    public DateTime? DecidedAt { get; init; }

    // Context (the employee's appraisal outcome — AC-1 workspace row).
    public decimal? FinalScore { get; init; }
    public ReviewFlag ManagerFlag { get; init; }
    public string ManagerFlagName { get; init; } = string.Empty;

    public IReadOnlyList<RecommendationApproverDto> Approvers { get; init; } = [];
    public IReadOnlyList<RecommendationEventDto> Events { get; init; } = [];
}

/// <summary>
/// One row of the recommendation workspace (US-PRF-010 AC-1): an employee in a completed cycle with their final
/// score, current grade/band/title/compensation, tenure, manager flag (US-PRF-003), and their existing
/// recommendation (null when none yet). HR sees all rows; a manager sees only their direct reports (AC-5).
/// </summary>
public sealed record RecommendationWorkspaceRowDto
{
    public Guid EmployeeId { get; init; }
    public string EmployeeName { get; init; } = string.Empty;
    public string EmployeeNo { get; init; } = string.Empty;
    public Guid DepartmentId { get; init; }
    public string DepartmentName { get; init; } = string.Empty;
    public string? CurrentGrade { get; init; }
    public string? CurrentTitle { get; init; }
    public decimal? CurrentCompensation { get; init; }
    public int TenureMonths { get; init; }
    public decimal? FinalScore { get; init; }
    public ReviewFlag ManagerFlag { get; init; }
    public string ManagerFlagName { get; init; } = string.Empty;
    public Guid? ManagerReviewId { get; init; }

    /// <summary>The existing recommendation for this employee in the cycle, if any (AC-1/AC-5 status column).</summary>
    public RecommendationDto? Recommendation { get; init; }
}

/// <summary>The paginated recommendation workspace (US-PRF-010 AC-1, NFR-4 pagination).</summary>
public sealed record RecommendationWorkspaceDto
